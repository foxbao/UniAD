def collect_queue_indices(info_list: List[dict], token2index: Dict[str, int],
                          raw_index: int, queue_length: int,
                          max_time_gap: float) -> Optional[List[int]]:
    if queue_length <= 1:
        return [raw_index]

    current = info_list[raw_index]
    scene_token = current.get('scene_token')
    indices = [raw_index]
    cursor = current
    prev_token = current.get('prev', '')
    for _ in range(queue_length - 1):
        if not prev_token:
            return None
        prev_index = token2index.get(prev_token)
        if prev_index is None:
            return None
        prev_info = info_list[prev_index]
        if prev_info.get('scene_token') != scene_token:
            return None
        dt = abs(float(cursor.get('timestamp', 0.0)) -
                 float(prev_info.get('timestamp', 0.0)))
        if dt > max_time_gap:
            return None
        indices.append(prev_index)
        cursor = prev_info
        prev_token = prev_info.get('prev', '')

    indices.reverse()
    return indices


def filter_infos_like_dataset(info_list: List[dict], dataset_cfg):
    dataset_type = dataset_cfg.get('type', '')
    queue_length = int(dataset_cfg.get('queue_length', 1))
    max_time_gap = float(dataset_cfg.get('max_time_gap', 1.0))
    if dataset_type != 'KlBEVFormerDataset' or queue_length <= 1:
        return info_list, list(range(len(info_list)))

    token2index = {
        info.get('token'): idx
        for idx, info in enumerate(info_list)
        if info.get('token')
    }
    valid_raw_indices = [
        idx for idx in range(len(info_list))
        if collect_queue_indices(info_list, token2index, idx, queue_length,
                                 max_time_gap) is not None
    ]
    filtered_infos = [info_list[idx] for idx in valid_raw_indices]
    return filtered_infos, valid_raw_indices


def resolve_lidar_path(cfg: Config, dataset_cfg, info: dict) -> str:
    data_root = dataset_cfg.get('data_root', cfg.get('data_root', ''))
    data_prefix = dataset_cfg.get('data_prefix', cfg.get('data_prefix', {}))
    pts_prefix = data_prefix.get('pts', '')
    lidar_info = info.get('lidar_points', {})
    lidar_path = lidar_info.get('lidar_path', info.get('lidar_path'))
    if lidar_path is None:
        raise KeyError('info does not contain lidar path')
    if osp.isabs(lidar_path) or osp.exists(lidar_path):
        return lidar_path
    return osp.join(data_root, pts_prefix, lidar_path)


def load_points(cfg: Config, dataset_cfg, info: dict) -> np.ndarray:
    lidar_path = resolve_lidar_path(cfg, dataset_cfg, info)
    lidar_info = info.get('lidar_points', {})
    num_feats = int(lidar_info.get('num_pts_feats',
                                   info.get('num_features', 4)))
    points = np.fromfile(lidar_path, dtype=np.float32)
    return points.reshape(-1, num_feats)


def map_label(label: int, label_mapping: Optional[List[int]],
              num_classes: int) -> int:
    label = int(label)
    if label_mapping is not None:
        if label < 0 or label >= len(label_mapping):
            return -1
        label = int(label_mapping[label])
    if label < 0 or label >= num_classes:
        return -1
    return label


def gt_arrays_from_info(info: dict, dataset_cfg, class_names: Sequence[str],
                        label_mapping: Optional[List[int]]) -> Dict[str, np.ndarray]:
    use_valid_flag = bool(dataset_cfg.get('use_valid_flag', False))
    instances = info.get('instances', [])
    boxes = []
    labels = []

    if instances:
        for inst in instances:
            raw_label = inst.get('bbox_label_3d', inst.get('bbox_label', -1))
            label = map_label(raw_label, label_mapping, len(class_names))
            if label < 0:
                continue
            valid = bool(inst.get('bbox_3d_isvalid', True)) if use_valid_flag \
                else int(inst.get('num_lidar_pts', 1)) > 0
            if not valid:
                continue
            box = np.asarray(inst['bbox_3d'], dtype=np.float32)
            vel = np.asarray(inst.get('velocity', [0.0, 0.0]),
                             dtype=np.float32)
            if box.shape[0] == 7:
                box = np.concatenate([box, vel[:2]], axis=0)
            elif box.shape[0] >= 9:
                box = box.copy()
                box[7:9] = vel[:2]
            if box.shape[0] < 9:
                box = np.pad(box, (0, 9 - box.shape[0]))
            boxes.append(box[:9])
            labels.append(label)
    elif 'gt_boxes' in info:
        gt_boxes = np.asarray(info['gt_boxes'], dtype=np.float32)
        gt_names = info.get('gt_names', [])
        valid_flags = info.get('valid_flag', [True] * len(gt_boxes))
        name_to_label = {name: idx for idx, name in enumerate(class_names)}
        for box, name, valid in zip(gt_boxes, gt_names, valid_flags):
            if use_valid_flag and not valid:
                continue
            label = name_to_label.get(str(name), -1)
            if label < 0:
                continue
            if box.shape[0] < 9:
                box = np.pad(box, (0, 9 - box.shape[0]))
            boxes.append(box[:9])
            labels.append(label)

    if not boxes:
        return empty_arrays()
    return dict(
        boxes=np.asarray(boxes, dtype=np.float32),
        labels=np.asarray(labels, dtype=np.int64),
        scores=np.ones((len(boxes),), dtype=np.float32))


def empty_arrays() -> Dict[str, np.ndarray]:
    return dict(
        boxes=np.zeros((0, 9), dtype=np.float32),
        labels=np.zeros((0,), dtype=np.int64),
        scores=np.zeros((0,), dtype=np.float32))


def tensor_to_numpy(value) -> np.ndarray:
    if isinstance(value, torch.Tensor):
        return value.detach().cpu().numpy()
    return np.asarray(value)


def boxes_to_numpy(boxes_3d) -> np.ndarray:
    if boxes_3d is None:
        return np.zeros((0, 9), dtype=np.float32)
    if hasattr(boxes_3d, 'tensor'):
        boxes = boxes_3d.tensor.detach().cpu().numpy()
    else:
        boxes = tensor_to_numpy(boxes_3d)
    boxes = boxes.astype(np.float32)
    if boxes.ndim == 1:
        boxes = boxes.reshape(1, -1)
    if boxes.shape[1] < 9:
        pad = np.zeros((boxes.shape[0], 9 - boxes.shape[1]), dtype=boxes.dtype)
        boxes = np.concatenate([boxes, pad], axis=1)
    return boxes[:, :9]


def unwrap_pkl_result(result):
    if isinstance(result, dict) and 'pts_bbox' in result:
        return result['pts_bbox']
    return result


def pred_arrays_from_pkl_result(result, score_thr: float,
                                topk: int) -> Dict[str, np.ndarray]:
    result = unwrap_pkl_result(result)
    if not isinstance(result, dict):
        return empty_arrays()
    boxes = boxes_to_numpy(result.get('boxes_3d'))
    scores = tensor_to_numpy(result.get('scores_3d', np.zeros((len(boxes),))))
    labels = tensor_to_numpy(result.get('labels_3d', np.zeros((len(boxes),))))
    scores = scores.astype(np.float32).reshape(-1)
    labels = labels.astype(np.int64).reshape(-1)
    if len(boxes) == 0:
        return empty_arrays()
    order = np.argsort(-scores)
    keep = order[scores[order] >= score_thr][:topk]
    return dict(boxes=boxes[keep], labels=labels[keep], scores=scores[keep])


def quat_to_yaw(quat: Sequence[float]) -> float:
    w, x, y, z = [float(v) for v in quat]
    siny_cosp = 2.0 * (w * z + x * y)
    cosy_cosp = 1.0 - 2.0 * (y * y + z * z)
    return math.atan2(siny_cosp, cosy_cosp)


def pred_arrays_from_json(entries: List[dict], class_names: Sequence[str],
                          score_thr: float, topk: int) -> Dict[str, np.ndarray]:
    name_to_label = {name: idx for idx, name in enumerate(class_names)}
    kept = [
        item for item in entries
        if float(item.get('detection_score', 0.0)) >= score_thr
        and item.get('detection_name') in name_to_label
    ]
    kept.sort(key=lambda item: float(item.get('detection_score', 0.0)),
              reverse=True)
    kept = kept[:topk]
    if not kept:
        return empty_arrays()

    boxes = []
    labels = []
    scores = []
    for item in kept:
        x, y, z = item['translation']
        w, l, h = item['size']
        yaw = quat_to_yaw(item['rotation'])
        vx, vy = item.get('velocity', [0.0, 0.0])
        boxes.append([x, y, z, l, w, h, yaw, vx, vy])
        labels.append(name_to_label[item['detection_name']])
        scores.append(float(item['detection_score']))
    return dict(
        boxes=np.asarray(boxes, dtype=np.float32),
        labels=np.asarray(labels, dtype=np.int64),
        scores=np.asarray(scores, dtype=np.float32))


