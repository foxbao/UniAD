def sample_indices(total: int, max_frames: int,
                   indices: Optional[Sequence[int]]) -> List[int]:
    if indices:
        out = []
        for idx in indices:
            if idx < 0 or idx >= total:
                raise IndexError(f'Index {idx} out of range 0..{total - 1}')
            out.append(int(idx))
        return out
    if max_frames == 0 or max_frames >= total:
        return list(range(total))
    return list(range(max_frames))


def compute_box_corners_bev(boxes: np.ndarray) -> np.ndarray:
    if boxes.size == 0:
        return np.zeros((0, 4, 2), dtype=np.float32)
    corners = []
    for box in boxes:
        x, y, _, l, w, _, yaw = box[:7]
        c = math.cos(float(yaw))
        s = math.sin(float(yaw))
        rot = np.array([[c, -s], [s, c]], dtype=np.float32)
        local = np.array([
            [l / 2, w / 2],
            [l / 2, -w / 2],
            [-l / 2, -w / 2],
            [-l / 2, w / 2],
        ], dtype=np.float32)
        corners.append(local @ rot.T + np.array([x, y], dtype=np.float32))
    return np.stack(corners, axis=0)


def lidar_xy_to_display(xy: np.ndarray) -> np.ndarray:
    disp = np.empty_like(xy, dtype=np.float32)
    disp[..., 0] = -xy[..., 1]
    disp[..., 1] = xy[..., 0]
    return disp


def draw_boxes(ax, boxes: np.ndarray, labels: np.ndarray,
               scores: Optional[np.ndarray], class_names: Sequence[str],
               color: str, vel_scale: float, min_vel_draw: float,
               annotate: bool = False, alpha: float = 1.0) -> None:
    if boxes.size == 0:
        return

    corners = compute_box_corners_bev(boxes)
    for idx, box in enumerate(boxes):
        poly = corners[idx]
        poly_disp = lidar_xy_to_display(poly)
        closed_disp = np.concatenate([poly_disp, poly_disp[:1]], axis=0)
        ax.plot(closed_disp[:, 0], closed_disp[:, 1],
                color=color, linewidth=1.4, alpha=alpha)

        center_xy_disp = lidar_xy_to_display(
            np.array([[box[0], box[1]]], dtype=np.float32))[0]
        center_x = float(center_xy_disp[0])
        center_y = float(center_xy_disp[1])

        yaw = float(box[6])
        heading_len = min(max(float(box[3]) * 0.22, 0.45), 1.35)
        heading_vec_lidar = np.array(
            [[math.cos(yaw), math.sin(yaw)]], dtype=np.float32)
        heading_vec_disp = lidar_xy_to_display(heading_vec_lidar)[0]
        ax.plot(
            [center_x, center_x + float(heading_vec_disp[0]) * heading_len],
            [center_y, center_y + float(heading_vec_disp[1]) * heading_len],
            color=color, linewidth=0.9, linestyle='--', alpha=0.6)

        vx, vy = float(box[7]), float(box[8])
        speed = math.hypot(vx, vy)
        if speed >= min_vel_draw:
            vel_disp = lidar_xy_to_display(
                np.array([[vx, vy]], dtype=np.float32))[0]
            dx = float(vel_disp[0]) * vel_scale
            dy = float(vel_disp[1]) * vel_scale
            disp_len = math.hypot(dx, dy)
            ax.arrow(
                center_x, center_y, dx, dy,
                color=color,
                width=min(max(disp_len * 0.012, 0.015), 0.05),
                head_width=min(max(disp_len * 0.14, 0.12), 0.6),
                head_length=min(max(disp_len * 0.22, 0.18), 0.9),
                length_includes_head=True,
                alpha=alpha)

        if annotate:
            label = int(labels[idx])
            label_name = class_names[label] if 0 <= label < len(class_names) \
                else str(label)
            score_text = '' if scores is None else f' {float(scores[idx]):.2f}'
            ax.text(center_x, center_y,
                    f'{label_name}{score_text} {speed:.2f}m/s',
                    color=color, fontsize=6, ha='left', va='bottom',
                    alpha=alpha)


def render_frame(points: np.ndarray, gt_data: Dict[str, np.ndarray],
                 pred_data: Dict[str, np.ndarray], class_names: Sequence[str],
                 save_path: str, title_id: str, pc_range: Sequence[float],
                 vel_scale: float, min_vel_draw: float, point_stride: int,
                 annotate: bool) -> None:
    x_min, y_min, _, x_max, y_max, _ = [float(v) for v in pc_range]
    disp_x_min, disp_x_max = -y_max, -y_min
    disp_y_min, disp_y_max = x_min, x_max

    fig, ax = plt.subplots(figsize=(12, 8), dpi=160)
    fig.patch.set_facecolor('black')
    ax.set_facecolor('black')

    pts = points[::point_stride, :3]
    if len(pts):
        pts_disp = lidar_xy_to_display(pts[:, :2])
        ax.scatter(pts_disp[:, 0], pts_disp[:, 1], s=0.12, c='white',
                   alpha=0.35, linewidths=0)

    draw_boxes(ax, gt_data['boxes'], gt_data['labels'], None, class_names,
               color='#00ff88', vel_scale=vel_scale,
               min_vel_draw=min_vel_draw, annotate=False, alpha=0.95)
    draw_boxes(ax, pred_data['boxes'], pred_data['labels'],
               pred_data['scores'], class_names, color='#ff4d4d',
               vel_scale=vel_scale, min_vel_draw=min_vel_draw,
               annotate=annotate, alpha=0.95)

    ax.plot(0.0, 0.0, marker='o', markersize=4, color='#ffd166')
    ax.arrow(0.0, 0.0, 0.0, 3.0, color='#ffd166', width=0.03,
             head_width=0.5, head_length=0.6, length_includes_head=True)

    ax.set_xlim(disp_x_min, disp_x_max)
    ax.set_ylim(disp_y_min, disp_y_max)
    ax.set_aspect('equal', adjustable='box')
    ax.set_xlabel('Lateral (m)', color='white')
    ax.set_ylabel('Forward (m)', color='white')
    ax.tick_params(colors='white', labelsize=8)
    for spine in ax.spines.values():
        spine.set_color('#888888')
    ax.grid(color='#444444', linestyle='--', linewidth=0.5, alpha=0.4)

    gt_speed = np.linalg.norm(gt_data['boxes'][:, 7:9], axis=1) \
        if len(gt_data['boxes']) else np.zeros((0,), dtype=np.float32)
    pred_speed = np.linalg.norm(pred_data['boxes'][:, 7:9], axis=1) \
        if len(pred_data['boxes']) else np.zeros((0,), dtype=np.float32)
    ax.set_title(
        f'KL BEV velocity | {title_id}\n'
        f'GT={len(gt_data["boxes"])} mean_speed={gt_speed.mean():.2f} m/s | '
        f'Pred={len(pred_data["boxes"])} '
        f'mean_speed={pred_speed.mean():.2f} m/s',
        color='white',
        fontsize=10)

    legend_lines = [
        plt.Line2D([0], [0], color='#00ff88', lw=2),
        plt.Line2D([0], [0], color='#ff4d4d', lw=2),
        plt.Line2D([0], [0], color='#ffd166', lw=2),
    ]
    ax.legend(legend_lines,
              ['GT boxes + velocity', 'Pred boxes + velocity', 'Ego heading'],
              loc='upper right', facecolor='black', edgecolor='#888888',
              labelcolor='white', fontsize=8)

    fig.tight_layout()
    fig.savefig(save_path, facecolor=fig.get_facecolor(), bbox_inches='tight')
    plt.close(fig)


def safe_token(token: str) -> str:
    return str(token).replace('/', '_').replace('\\', '_')


def selected_indices(info_list: List[dict], args) -> List[int]:
    if args.tokens:
        token_to_idx = {
            str(info.get('token', idx)): idx for idx, info in enumerate(info_list)
        }
        missing = [token for token in args.tokens if token not in token_to_idx]
        if missing:
            raise KeyError(f'Tokens not found in infos: {missing}')
        return [token_to_idx[token] for token in args.tokens]
    return sample_indices(len(info_list), args.max_frames, args.indices)


