def write_webm_video(out_dir: str, fps: float = 3.0,
                     crf: int = 34) -> None:
    if fps <= 0:
        return
    output_path = osp.join(out_dir, 'velocity_vis.webm')
    input_glob = osp.join(out_dir, '*.png')
    cmd = [
        'ffmpeg',
        '-y',
        '-framerate',
        str(float(fps)),
        '-pattern_type',
        'glob',
        '-i',
        input_glob,
        '-vf',
        'pad=ceil(iw/2)*2:ceil(ih/2)*2',
        '-c:v',
        'libvpx-vp9',
        '-b:v',
        '0',
        '-crf',
        str(int(crf)),
        output_path,
    ]
    try:
        subprocess.run(cmd, check=True)
    except FileNotFoundError:
        print('[WARN] ffmpeg not found; skipped WebM generation.')
    except subprocess.CalledProcessError as exc:
        print(f'[WARN] ffmpeg failed with exit code {exc.returncode}; '
              'skipped WebM generation.')


def main():
    args = parse_args()
    cfg = Config.fromfile(args.config)
    dataset_cfg = get_dataset_cfg(cfg, args.split)
    class_names = get_class_names(cfg, dataset_cfg)
    label_mapping = get_label_mapping(cfg, dataset_cfg)
    raw_info_list = load_info_list(resolve_info_path(cfg, dataset_cfg))
    info_list, raw_indices = filter_infos_like_dataset(raw_info_list,
                                                       dataset_cfg)
    if len(info_list) != len(raw_info_list):
        print(f'[INFO] dataset queue filter kept {len(info_list)}/'
              f'{len(raw_info_list)} infos')
    indices = selected_indices(info_list, args)

    pkl_results = None
    json_results = None
    if args.results_pkl:
        pkl_results = load_results_pkl(args.results_pkl)
        if len(pkl_results) != len(info_list):
            print(f'[WARN] results length {len(pkl_results)} != '
                  f'dataset info length {len(info_list)}')
    else:
        with open(args.results_json, 'r') as f:
            payload = json.load(f)
        json_results = payload['results']

    mmcv.mkdir_or_exist(args.out_dir)
    summary = []
    frame_files = []
    for idx in indices:
        info = info_list[idx]
        raw_index = raw_indices[idx]
        token = str(info.get('token', idx))
        out_file = osp.join(args.out_dir, f'{idx:06d}_{safe_token(token)}.png')
        if args.skip_existing and osp.exists(out_file):
            print(f'[SKIP] {out_file}')
            summary.append(dict(index=idx, token=token, out_file=out_file,
                                skipped=True))
            frame_files.append(out_file)
            continue

        points = load_points(cfg, dataset_cfg, info)
        gt_data = gt_arrays_from_info(info, dataset_cfg, class_names,
                                      label_mapping)
        if pkl_results is not None:
            if idx >= len(pkl_results):
                print(f'[WARN] missing pkl result for index {idx}, skip')
                continue
            pred_data = pred_arrays_from_pkl_result(
                pkl_results[idx], args.score_thr, args.topk)
        else:
            pred_data = pred_arrays_from_json(
                json_results.get(token, []), class_names,
                args.score_thr, args.topk)

        render_frame(
            points=points,
            gt_data=gt_data,
            pred_data=pred_data,
            class_names=class_names,
            save_path=out_file,
            title_id=f'idx={idx} raw_idx={raw_index} token={token}',
            pc_range=cfg.point_cloud_range,
            vel_scale=args.vel_scale,
            min_vel_draw=args.min_vel_draw,
            point_stride=args.point_stride,
            annotate=args.annotate)
        summary.append(dict(
            index=int(idx),
            raw_index=int(raw_index),
            token=token,
            out_file=out_file,
            num_gt=int(len(gt_data['boxes'])),
            num_pred=int(len(pred_data['boxes']))))
        frame_files.append(out_file)
        print(f'[OK] {out_file}')

    with open(osp.join(args.out_dir, 'summary.json'), 'w') as f:
        json.dump(summary, f, indent=2)
    write_html_player(args.out_dir, frame_files)
    write_webm_video(args.out_dir, fps=args.webm_fps, crf=args.webm_crf)


if __name__ == '__main__':
    main()
